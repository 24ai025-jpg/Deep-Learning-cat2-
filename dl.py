import os, torch, numpy as np, pandas as pd, matplotlib.pyplot as plt, torch.nn as nn
from torch.utils.data import TensorDataset, DataLoader
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error
os.makedirs('data', exist_ok=True)
data_path = 'data/traffic_volume.csv'
if not os.path.exists(data_path):
    np.random.seed(42)
    dates = pd.date_range("2022-01-01", periods=2000, freq="h")
    h = dates.hour.values
    daily = 3000 * np.sin(np.pi * (h - 4) / 12)
    daily[h < 5], daily[h > 22] = 400, 600
    traffic = np.maximum(200, 1500 + daily + np.random.normal(0, 200, 2000))
    temp = 285 + 10 * np.sin(2 * np.pi * np.arange(2000) / 24) + np.random.normal(0, 2, 2000)
    pd.DataFrame({
        "date_time": dates.strftime("%Y-%m-%d %H:%M:%S"), "temp": np.round(temp, 2),
        "rain_1h": np.random.choice([0.0, 0.0, 0.0, 0.5, 1.2, 3.0], 2000),
        "clouds_all": np.random.randint(0, 100, 2000), "weather_main": "Clear",
        "traffic_volume": traffic.astype(int)
    }).to_csv(data_path, index=False)
np.random.seed(42); torch.manual_seed(42)
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
df = pd.read_csv(data_path)
df['date_time'] = pd.to_datetime(df['date_time'])
df['hour'], df['day_of_week'] = df['date_time'].dt.hour, df['date_time'].dt.dayofweek
features = ['traffic_volume', 'hour', 'day_of_week', 'temp', 'rain_1h', 'clouds_all']
sc_X, sc_y = MinMaxScaler(), MinMaxScaler()
scaled_X = sc_X.fit_transform(df[features].values)
scaled_y = sc_y.fit_transform(df[['traffic_volume']].values)
W_SIZE = 24
X, y = [], []
for i in range(len(scaled_X) - W_SIZE):
    X.append(scaled_X[i:i+W_SIZE])
    y.append(scaled_y[i+W_SIZE])
X, y = np.array(X), np.array(y)

split = int(len(X) * 0.8)
X_tr, X_te = torch.tensor(X[:split], dtype=torch.float32), torch.tensor(X[split:], dtype=torch.float32)
y_tr, y_te = torch.tensor(y[:split], dtype=torch.float32), torch.tensor(y[split:], dtype=torch.float32)
test_ts = df['date_time'].values[W_SIZE + split:]

train_loader = DataLoader(TensorDataset(X_tr, y_tr), batch_size=32, shuffle=True)
test_loader = DataLoader(TensorDataset(X_te, y_te), batch_size=32, shuffle=False)
class TrafficLSTM(nn.Module):
    def __init__(self):
        super().__init__()
        self.lstm = nn.LSTM(6, 64, 2, batch_first=True, dropout=0.2)
        self.fc = nn.Sequential(nn.Linear(64, 32), nn.ReLU(), nn.Linear(32, 1))
    def forward(self, x):
        out, _ = self.lstm(x)
        return self.fc(out[:, -1, :])

model = TrafficLSTM().to(device)
criterion, optimizer = nn.MSELoss(), torch.optim.Adam(model.parameters(), lr=0.003)

train_losses = []
for epoch in range(1, 26):
    model.train(); r_loss = 0.0
    for bx, by in train_loader:
        bx, by = bx.to(device), by.to(device)
        optimizer.zero_grad()
        loss = criterion(model(bx), by)
        loss.backward(); optimizer.step()
        r_loss += loss.item() * bx.size(0)
    train_losses.append(r_loss / len(X_tr))

# 4. Evaluation
model.eval(); preds = []
with torch.no_grad():
    for bx, _ in test_loader:
        preds.extend(model(bx.to(device)).cpu().numpy())

act_vol = sc_y.inverse_transform(y_te.numpy())
pred_vol = sc_y.inverse_transform(np.array(preds))
print(f"MAE: {mean_absolute_error(act_vol, pred_vol):.1f} | RMSE: {np.sqrt(mean_squared_error(act_vol, pred_vol)):.1f}")

# Quick plot of last 96 hours
plt.figure(figsize=(10, 4))
plt.plot(test_ts[-96:], act_vol[-96:], 'k-', label='Actual')
plt.plot(test_ts[-96:], pred_vol[-96:], 'r--', label='Predicted')
plt.title('Hourly Traffic Volume Forecast (Last 4 Days)'); plt.legend(); plt.grid(True, alpha=0.3)
plt.show()